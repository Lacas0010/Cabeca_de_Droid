/**
 * Retorna a string traduzida para a chave solicitada no idioma ativo.
 */
export function t(key, fallback = "") {
    if (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key]) {
        return TRANSLATIONS[currentLang][key];
    }
    if (TRANSLATIONS["pt"] && TRANSLATIONS["pt"][key]) {
        return TRANSLATIONS["pt"][key];
    }
    return fallback || key;
}

/**
 * Retorna o código do idioma ativo ('pt' ou 'en').
 */
export function getLanguage() {
    return currentLang;
}

/**
 * Define o novo idioma ativo, persiste no localStorage e reaplica a tradução na UI.
 */
export function setLanguage(newLang) {
    if (!TRANSLATIONS[newLang]) return;
    currentLang = newLang;
    window.currentLang = newLang;
    localStorage.setItem("app_lang", newLang);
    document.documentElement.lang = newLang === "pt" ? "pt-BR" : "en-US";

    // Atualiza controles de UI de seleção de idioma
    updateLanguageControls();

    // Aplica traduções no DOM
    applyTranslations();

    // Notifica outros módulos via evento customizado
    window.dispatchEvent(new CustomEvent("app:languageChanged", { detail: { lang: newLang } }));
}

/**
 * Atualiza visualmente botões e seletores de idioma no cabeçalho e configurações.
 */
function updateLanguageControls() {
    // Botões no Desktop
    document.querySelectorAll(".lang-btn").forEach(btn => {
        const lang = btn.getAttribute("data-lang");
        if (lang === currentLang) {
            btn.classList.add("active");
        } else {
            btn.classList.remove("active");
        }
    });

    // Indicador no Mobile
    const mobileLabel = document.getElementById("mobile-lang-label");
    if (mobileLabel) {
        mobileLabel.textContent = currentLang.toUpperCase();
    }

    // Select na tela de configurações
    const cfgSelect = document.getElementById("cfg-app-language");
    if (cfgSelect && cfgSelect.value !== currentLang) {
        cfgSelect.value = currentLang;
    }
}

/**
 * Percorre o DOM traduzindo elementos marcados com data-i18n.
 */
export function applyTranslations(container = document) {
    if (!container) return;

    // Textos de nós de texto
    const elements = container.querySelectorAll("[data-i18n]");
    elements.forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (key) {
            const translation = t(key);
            if (translation) {
                const icon = el.querySelector("i, img, svg");
                if (icon) {
                    let textNodeFound = false;
                    el.childNodes.forEach(child => {
                        if (child.nodeType === Node.TEXT_NODE && child.textContent.trim()) {
                            child.textContent = " " + translation.trim();
                            textNodeFound = true;
                        }
                    });
                    if (!textNodeFound) {
                        const targetSpan = el.querySelector("span:not([data-i18n])");
                        if (targetSpan) {
                            targetSpan.textContent = translation;
                        } else {
                            el.textContent = translation;
                        }
                    }
                } else {
                    el.textContent = translation;
                }
            }
        }
    });

    // Placeholders de inputs
    const placeholders = container.querySelectorAll("[data-i18n-placeholder]");
    placeholders.forEach(el => {
        const key = el.getAttribute("data-i18n-placeholder");
        if (key) {
            const translation = t(key);
            if (translation) {
                el.placeholder = translation;
            }
        }
    });

    // Títulos / Tooltips
    const titles = container.querySelectorAll("[data-i18n-title]");
    titles.forEach(el => {
        const key = el.getAttribute("data-i18n-title");
        if (key) {
            const translation = t(key);
            if (translation) {
                el.title = translation;
            }
        }
    });
}

/**
 * Inicializa o módulo i18n na carga do aplicativo.
 */
export function initI18n() {
    // Configura o atributo lang do HTML
    document.documentElement.lang = currentLang === "pt" ? "pt-BR" : "en-US";

    // Adiciona listener para botões de alternância de idioma
    document.addEventListener("click", e => {
        const langBtn = e.target.closest(".lang-btn");
        if (langBtn) {
            const lang = langBtn.getAttribute("data-lang");
            if (lang) {
                setLanguage(lang);
            }
            return;
        }

        const mobileToggle = e.target.closest("#mobile-lang-toggle");
        if (mobileToggle) {
            const nextLang = currentLang === "pt" ? "en" : "pt";
            setLanguage(nextLang);
        }
    });

    // Atualiza controles e aplica traduções iniciais
    updateLanguageControls();
    applyTranslations();
}

// Expõe na janela global para interoperabilidade
